/// The typeahead's candidates for a `:token`: name (or keyword) contains the
/// token, shortest names first when the token is empty (the everyday few
/// lead). Capped — the strip stays a strip.
pub fn candidates(token: &str) -> Vec<&'static Emoji> {
    let t = token.to_lowercase();
    let mut hits: Vec<&Emoji> = EMOJI
        .iter()
        .filter(|e| e.name.contains(&t) || e.k.iter().any(|k| k.contains(&t)))
        .collect();
    hits.truncate(12);
    hits
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn token_matches_names_and_keywords() {
        // name match
        assert!(candidates("joy").iter().any(|e| e.name == "joy"));
        // keyword match ("lol" rides joy's k)
        assert!(candidates("lol").iter().any(|e| e.name == "joy"));
        // empty token = the everyday few lead
        assert_eq!(candidates("").len(), 12);
        // no hit
        assert!(candidates("zzzzz-nope").is_empty());
        // the inserted form is well-formed shortcode text
        for e in candidates("thumbs") {
            assert!(!e.char.is_empty() && !e.name.contains(':'));
        }
    }
}
