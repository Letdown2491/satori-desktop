#!/bin/sh
# Regenerates the app icon from the in-app glyph (icons.rs enso_glyph):
# the same arc — start 60°, sweep 320°, radius 9.2 → 8.1 on the 24-unit
# grid — on a washi disc with the hairline ring. Palette = theme.rs LIGHT.
# Output: one SVG (scalable) + the hicolor PNG sizes.
#
#	./generate.sh && for s in 512 256 128 64 48 32; do
#	  magick -background none io.github.Letdown2491.satori.svg \
#	    -resize ${s}x${s} ${s}x${s}/apps/io.github.Letdown2491.satori.png
#	done
set -e
cd "$(dirname "$0")"

PATH_D=$(awk 'BEGIN {
    start = 60 * atan2(0, -1) / 180
    sweep = 320 * atan2(0, -1) / 180
    n = 80
    scale = 512.0 / 24.0
    for (i = 0; i <= n; i++) {
        t = i / n
        a = start + sweep * t
        r = (9.2 - 1.1 * t) * scale
        printf "%s%.2f %.2f", (i == 0 ? "M " : " L "), 256 + r * cos(a), 256 + r * sin(a)
    }
}')

cat > io.github.Letdown2491.satori.svg <<EOF
<!-- Satori: washi disc, hairline ring, ink ensō. Generated by generate.sh —
     palette from theme.rs LIGHT (washi/ink/hairline). -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <circle cx="256" cy="256" r="248" fill="#e3dac4"/>
  <circle cx="256" cy="256" r="246" fill="none" stroke="#c9bd9f" stroke-width="4"/>
  <path d="${PATH_D}" fill="none" stroke="#191714" stroke-width="51.2" stroke-linecap="round"/>
</svg>
EOF

echo "wrote io.github.Letdown2491.satori.svg"
